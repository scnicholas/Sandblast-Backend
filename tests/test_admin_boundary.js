'use strict';
const assert=require('node:assert/strict');
const Gateway=require('../Data/marion/runtime/MarionAdminConsoleGateway.js');
const Safety=require('../Data/marion/runtime/marionAdminRuntimeSafety.js');
let count=0; const check=(cond,label)=>{assert.ok(cond,label);count++};
const ctx={adminVerified:true,sessionVerified:true,verified:true,verifiedBy:'server_middleware',role:'owner',sessionId:'sid-123'};
const missing={...ctx,sessionVerified:false};
check(Safety.isServerVerifiedOwner(ctx),'verified owner');
check(!Safety.isServerVerifiedOwner(missing),'missing verification');
check(!Safety.isServerVerifiedOwner({...ctx,role:'guest'}),'guest role');
check(Safety.isServerVerifiedOwner({...ctx,adminVerified:undefined}),'server principal compatible without admin flag');
check(!Safety.isServerVerifiedOwner({...ctx,verifiedBy:'client'}),'client verified');
check(Safety.privatePartitionKey({},ctx).startsWith('private:admin:'),'private partition');
check(Safety.privatePartitionKey({sessionId:'spoof'},missing)==='private:admin:unverified','unverified partition');
(async()=>{
 const gw=new Gateway.MarionAdminConsoleGateway({marionRuntime:{handleAdminCommand:async()=>({ok:true})}});
 const denied=await gw.handleApprove({requestId:'r1'},{});check(denied.ok===false,'owner enforced');
 const direct=await gw.executeRuntimeCommand({type:'text',command:'deploy'},'high',Date.now());check(direct.ok===false,'runtime direct denied');
 const directCmd=await gw.executeCommand({command:'deploy'},'high',new Date().toISOString(),ctx);check(directCmd.ok===false,'executeCommand direct denied');
 const forged=await gw.handleCommand({command:'delete records',approvalToken:'fake',approvalId:'fake'},ctx);check(forged.ok===false,'forged approval token denied');
 const pending=await gw.handleCommand({command:'delete records'},ctx);check(pending.approvalRequired===true,'high risk pending');
 const id=pending.approvalId;check(typeof id==='string'&&id.length>0,'pending id');
 const other=await gw.handleApprove({approvalId:id},{...ctx,sessionId:'other'});check(other.ok===false,'wrong session cannot approve');
 const accepted=await gw.handleApprove({approvalId:id},ctx);check(accepted.approved===true,'owner can approve');
 const replay=await gw.handleApprove({approvalId:id},ctx);check(replay.ok===false,'approval replay denied');
 const voiceReq={command:'admin_voice_delivery_once',requestId:'voice-1'};
 const voice=await gw.handleCommand(voiceReq,ctx);check(voice.approvalRequired===true,'voice pending');
 const voiceApproval=await gw.handleApprove({approvalId:voice.approvalId},ctx);check(voiceApproval.approved===true,'voice approval');
 const wrong=gw.consumeAdminVoiceDeliveryApproval({...ctx,sessionId:'wrong'});check(wrong.adminVoiceDeliveryAllowed===false,'wrong session cannot consume');
 const once=gw.consumeAdminVoiceDeliveryApproval(ctx);check(once.consumedForThisTurn===true,'voice grant consumed');
 const twice=gw.consumeAdminVoiceDeliveryApproval(ctx);check(twice.adminVoiceDeliveryAllowed===false,'voice grant single-use');
 const noContext=await gw.handleCommand({command:'admin_voice_delivery_once'},{});check(noContext.ok===false,'anonymous voice forbidden');
 const forgedStatus=await gw.handleStatus({},{});check(forgedStatus.ok===false&&forgedStatus.final===false,'private status cannot be spoofed into final');
 const status=await gw.handleStatus({},ctx);check(status.ok===true,'verified status supported');
 const rejected=await gw.executeRuntimeCommand({type:'text',command:'disable everything'},'critical',Date.now());
 check(rejected.status===403&&rejected.ok===false&&rejected.spokenText===''&&rejected.canEmit===false,'denied runtime cannot speak');
 const external=await Gateway.handleCommand({command:'delete everything',approvalToken:'forged'},ctx);
 check(external.ok===false&&external.final===false,'exported command denies forged approval');
 const remote=await gw.handleCommand({command:'delete everything'},{...ctx,role:'remote_trusted_user'});
 check(remote.ok===false,'non-owner blocked');
 const voiceRequest2=await Gateway.defaultGateway.handleCommand({command:'admin_voice_delivery_once',requestId:'voice-2'},ctx);
 check(voiceRequest2.approvalRequired===true,'second voice pending');
 const voiceApproved2=await Gateway.defaultGateway.handleApprove({approvalId:voiceRequest2.approvalId},ctx);
 check(voiceApproved2.approved===true,'second voice approved');
 const consumedViaPublic=Gateway.consumeAdminVoiceRuntimeApproval({...ctx,sessionId:'wrong'});
 check(consumedViaPublic.adminVoiceDeliveryAllowed===false,'exported voice consume binds session');
 const consumed2=Gateway.consumeAdminVoiceRuntimeApproval(ctx);
 check(consumed2.consumedForThisTurn===true,'exported voice consumes once');
 const repeat2=Gateway.consumeAdminVoiceRuntimeApproval(ctx);
 check(repeat2.adminVoiceDeliveryAllowed===false,'exported voice cannot replay');
 console.log('PASS',count,'focused assertions');
})().catch(e=>{console.error(e.stack);process.exitCode=1});
